"""Заготовка з ПР10. Замініть цей файл своїм `pr10/app/drafting.py` і
допишіть те, що перелічено нижче.

Що додати в ПР11:

* `PROMPT_VERSION` — версія інструкції: рядок, який ви змінюєте разом
  з текстом інструкції (`"drafts-v1"`), хеш тексту інструкції або
  обидва. Вона йде в `Request.metadata`, у журнал і в ключ кешу;
  веб-рівень показує її на сторінці;
* `Request.metadata` — усе, що потрібно шлюзу, кешу й журналу, але не
  моделі: `request_id` звернення, `prompt_version`, `fresh`;
  ідентифікатори чернетки й HTTP-запиту додає `jobs.py`;
* що з запиту може потрапити в журнал: довжина повідомлень у символах,
  кількість фактів, хеш — а не текст клієнта й не факти з іменами й
  номерами.

Нижче — заготовка ПР10 без змін.

Що саме просимо в моделі: чернетка відповіді клієнтові.

Єдиний модуль, який знає предметну задачу — що оператор підтримки
«Сузірʼя» відповідає клієнтові за встановленими фактами. Шлюз
(`app/gateway.py`) і провайдери не знають, що генерують; фонова задача
(`app/jobs.py`) не знає, з чого складається запит. Тут складається
повідомлення для моделі з інструкції, звернення клієнта і фактів,
і тут вирішується, що з результатом не так.

Функції нижче — заготовки. Рішення з розділу 2 практичної роботи:

* що в системній інструкції: від чийого імені, якою мовою, якої
  довжини, що робити з фактами (спиратися лише на них) і що робити,
  коли фактів немає або вони не стосуються питання;
* як подати факти — списком, щоб модель не плутала їх зі словами
  клієнта; чи потрібна позначка, що текст клієнта — це цитата, а не
  інструкція;
* чи перевіряти чернетку кодом: наявність номера заявки з фактів,
  відсутність того, чого у фактах немає (суми, дати), довжина. Чернетку
  редагує людина, тож планка нижча, ніж у відповіді клієнтові з ПР9,
  але що саме оператор має побачити як попередження;
* `metadata`: що покласти в `Request.metadata`, щоб журнал і підставний
  провайдер знали, до якого звернення належить виклик.
"""

import re

from .providers.base import Request

PROMPT_VERSION = "drafts-v1"
SYSTEM_PROMPT = (
    "Ти помічник оператора підтримки «Сузірʼя». Склади коротку, "
    "ввічливу відповідь українською мовою від імені служби підтримки. "
    "Використовуй лише наведені факти. Не вигадуй дат, сум і номерів. "
    "Якщо фактів недостатньо, чесно скажи, що оператор має уточнити."
)


def build_request(sample: dict) -> Request:
    """Скласти запит до моделі за зразком звернення.

    `sample` — елемент `samples/requests.json`: текст клієнта, факти,
    які встановив оператор, ідентифікатор. Параметри генерації — з
    `app/gateway.py`.
    """
    from .gateway import MAX_TOKENS, TEMPERATURE

    facts = "\n".join(f"- {fact}" for fact in sample.get("facts", [])) or "- Підтверджених фактів немає."
    customer = sample.get("customer", "")
    user_message = (
        f"Ім'я клієнта: {customer}\n"
        "Звернення клієнта:\n"
        f"{sample.get('text', '')}\n\n"
        f"Факти оператора:\n{facts}\n\n"
        "Підготуй чернетку відповіді клієнтові."
    )
    return Request(
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_message},
        ],
        max_tokens=MAX_TOKENS,
        temperature=TEMPERATURE,
        metadata={
            "request_id": str(sample.get("id", "")),
            "prompt_version": PROMPT_VERSION,
            "facts_count": len(sample.get("facts", [])),
            "input_chars": len(user_message),
        },
    )


def check(text: str, sample: dict) -> list[str]:
    """Перевірити готову чернетку й повернути перелік попереджень для
    оператора; порожній список — зауважень немає."""
    warnings = []
    if not text.strip():
        warnings.append("Чернетка порожня.")
    if len(text) > 4000:
        warnings.append("Чернетка задовга — скоротіть її перед надсиланням.")
    source = " ".join([sample.get("text", ""), *map(str, sample.get("facts", []))])
    source_numbers = set(re.findall(r"\d[\d./-]*\d|\d", source))
    for number in sorted(set(re.findall(r"\d[\d./-]*\d|\d", text)) - source_numbers):
        warnings.append(f"Перевірте число «{number}»: його немає у зверненні чи фактах.")
    return warnings
