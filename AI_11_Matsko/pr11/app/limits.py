"""Заготовка з ПР10. Замініть цей файл своїм `pr10/app/limits.py`.

У ПР11 обмеження частоти не змінюється. Єдине доповнення на ваш розсуд
— запис відмов у журнал (наприклад, `rate_limit.rejected` з клієнтом і
`retry_after`), щоб аналіз бачив, хто впирається в ліміт. На час
прогону `eval/replay.py` ліміт у `.env` підніміть.

Нижче — заготовка ПР10 без змін.

Обмеження частоти звертань до власного API.

Ліміт провайдера — спільний на весь застосунок: якщо один користувач
сторінки натисне «скласти чернетку» двадцять разів за хвилину, 429 від
провайдера отримають усі. Тому веб-рівень обмежує кожного клієнта ще до
того, як запит дійде до шлюзу. Це інше обмеження, ніж `MAX_CONCURRENT`
у шлюзі: там — скільки звертань до провайдера виконується одночасно на
всіх, тут — скільки запитів за вікно часу дозволено одному.

Хто такий «клієнт», вирішує веб-рівень: сторінка надсилає свій
ідентифікатор у полі `client`. У справжньому застосунку це був би
користувач із сесії або ключ API.

Функції нижче — заготовки. Рішення з розділу 2 практичної роботи:

* алгоритм: ковзне вікно, вікно з фіксованим початком, кошик жетонів
  (token bucket). Що з них дає чесніше `retry_after`;
* що відповісти, коли ліміт вичерпано: відмовити одразу з 429 і
  `Retry-After` чи поставити в чергу з видимим місцем у ній. Для
  чернетки, яку оператор чекає, — що краще;
* звідки веб-рівень дізнається про відмову: виняток `RateLimited` чи
  значення, що повертається, — і хто перетворює його на HTTP-відповідь;
* чи потрібно колись «повертати» дозвіл (наприклад, якщо запит
  відхилено з іншої причини) і чи рахувати запити, які провалилися.
"""

import os
import threading
import time
from collections import defaultdict, deque

from dotenv import load_dotenv

load_dotenv()

PER_MINUTE = int(os.getenv("RATE_LIMIT_PER_MINUTE", "10"))
_lock = threading.Lock()
_requests: dict[str, deque[float]] = defaultdict(deque)


class RateLimited(Exception):
    """Ліміт вичерпано. `retry_after` — через скільки секунд пробувати."""

    def __init__(self, retry_after: float) -> None:
        super().__init__(f"ліміт вичерпано, повторіть через {retry_after:.0f} с")
        self.retry_after = retry_after


def settings() -> dict:
    """Чинні обмеження — для сторінки."""
    return {"per_minute": PER_MINUTE}


def acquire(client: str) -> None:
    """Зарахувати одне звертання клієнта або підняти `RateLimited`.

    Викликається веб-рівнем перед створенням кожної чернетки.
    """
    now = time.monotonic()
    with _lock:
        requests = _requests[client]
        while requests and now - requests[0] >= 60:
            requests.popleft()
        if len(requests) >= PER_MINUTE:
            raise RateLimited(max(1.0, 60 - (now - requests[0])))
        requests.append(now)
